import { afterEach, beforeEach, describe, expect, test } from 'bun:test';
import { appendFileSync, existsSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  expectedSnippetLines,
  removeMarkedContent,
  shortcutsNonInteractiveMessage,
  shortcutsUnansweredMessage,
} from './shortcuts.js';

const CLI = join(import.meta.dir, '..', 'genie.ts');
const MARKER = 'generated by genie-cli';

let dir: string;

/**
 * Simulate exactly what a PRE-FENCE `shortcuts install` appended: `\n` + the
 * bare snippet. Exercises the legacy uninstall lane that existing installs
 * from those releases still depend on.
 */
function simulateInstall(filePath: string): void {
  const snippet = expectedSnippetLines(filePath);
  if (snippet === null) throw new Error(`unmanaged file: ${filePath}`);
  appendFileSync(filePath, `\n${snippet.join('\n')}`);
}

function tmuxConf(): string {
  return join(dir, '.tmux.conf');
}

function zshrc(): string {
  return join(dir, '.zshrc');
}

function runShortcuts(args: string[], input: string): { code: number; stdout: string; stderr: string } {
  // Feed answers through a shell pipe: Bun.spawnSync's `input` delivers EOF to
  // the child's readline before any `line` event (Bun 1.3.9 quirk), but shell
  // pipes deliver both lines reliably.
  const stdinSource = input === '' ? '</dev/null' : `printf '%b' ${JSON.stringify(input)} |`;
  const cmd = `${stdinSource} ${JSON.stringify(process.execPath)} ${JSON.stringify(realpathSync(CLI))} ${args.join(' ')}`;
  const res = Bun.spawnSync(['/bin/sh', '-c', cmd], {
    stdout: 'pipe',
    stderr: 'pipe',
    timeout: 20_000,
    env: { ...process.env, HOME: dir, PATH: '/usr/bin:/bin' },
  });
  return { code: res.exitCode, stdout: res.stdout.toString(), stderr: res.stderr.toString() };
}

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), 'genie-shortcuts-'));
});

afterEach(() => {
  rmSync(dir, { recursive: true, force: true });
});

describe('removeMarkedContent', () => {
  test('removes exactly the installed block and restores the original file', () => {
    writeFileSync(tmuxConf(), 'set -g prefix C-a\n');
    const original = readFileSync(tmuxConf(), 'utf-8');
    simulateInstall(tmuxConf());

    const result = removeMarkedContent(tmuxConf(), MARKER);

    expect(result).toBe('removed');
    expect(readFileSync(tmuxConf(), 'utf-8')).toBe(original);
  });

  test('restores a .zshrc with pre-existing content byte-for-byte', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\nalias g=git\n');
    const original = readFileSync(zshrc(), 'utf-8');
    simulateInstall(zshrc());

    expect(removeMarkedContent(zshrc(), MARKER)).toBe('removed');
    expect(readFileSync(zshrc(), 'utf-8')).toBe(original);
  });

  test('leaves an empty file empty after the round-trip', () => {
    writeFileSync(tmuxConf(), '');
    simulateInstall(tmuxConf());

    expect(removeMarkedContent(tmuxConf(), MARKER)).toBe('removed');
    expect(readFileSync(tmuxConf(), 'utf-8')).toBe('');
  });

  test('preserves user lines that merely contain words like genie or stty -ixon', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    simulateInstall(zshrc());
    // User content AFTER the block, containing genie-adjacent words.
    appendFileSync(zshrc(), '\n# my personal genie wrapper\ngenie() { command genie "$@"; }\nalias xon="stty -ixon"\n');

    expect(removeMarkedContent(zshrc(), MARKER)).toBe('removed');
    const after = readFileSync(zshrc(), 'utf-8');
    expect(after).toContain('# my personal genie wrapper');
    expect(after).toContain('genie() { command genie "$@"; }');
    expect(after).toContain('alias xon="stty -ixon"');
    expect(after).not.toContain('genie-new-tab');
    expect(after).not.toContain('bind -x');
  });

  test("returns 'modified' and leaves the file untouched when the block was edited", () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    simulateInstall(zshrc());
    const path = zshrc();
    const edited = readFileSync(path, 'utf-8').replace('stty -ixon 2>/dev/null', 'stty -ixon');
    writeFileSync(path, edited);

    expect(removeMarkedContent(path, MARKER)).toBe('modified');
    expect(readFileSync(path, 'utf-8')).toBe(edited);
  });

  test("returns 'absent' for files without the marker or outside the managed set", () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    expect(removeMarkedContent(zshrc(), MARKER)).toBe('absent');

    writeFileSync(join(dir, 'custom.conf'), '# generated by genie-cli\n');
    expect(removeMarkedContent(join(dir, 'custom.conf'), MARKER)).toBe('absent');
  });

  test('is idempotent: a second removal is a no-op', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    simulateInstall(zshrc());
    expect(removeMarkedContent(zshrc(), MARKER)).toBe('removed');
    const afterFirst = readFileSync(zshrc(), 'utf-8');
    expect(removeMarkedContent(zshrc(), MARKER)).toBe('absent');
    expect(readFileSync(zshrc(), 'utf-8')).toBe(afterFirst);
  });

  test('preserves user-owned trailing blank lines after the block', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    simulateInstall(zshrc());
    // User appended content AFTER the block, deliberately ending in blank lines.
    appendFileSync(zshrc(), '\nalias g=git\n\n\n');

    expect(removeMarkedContent(zshrc(), MARKER)).toBe('removed');
    expect(readFileSync(zshrc(), 'utf-8')).toBe('export EDITOR=vim\n\nalias g=git\n\n\n');
  });

  test('a user-pasted copy of the marker line above the block does not shadow the real block', () => {
    writeFileSync(zshrc(), '# my note: generated by genie-cli blocks live below\nexport EDITOR=vim\n');
    const original = readFileSync(zshrc(), 'utf-8');
    simulateInstall(zshrc());

    expect(removeMarkedContent(zshrc(), MARKER)).toBe('removed');
    expect(readFileSync(zshrc(), 'utf-8')).toBe(original);
  });
});

describe('fenced blocks (current install format)', () => {
  /** Install via the real CLI so the file carries the current fenced format. */
  function cliInstall(): void {
    const res = runShortcuts(['shortcuts', 'install', '--yes'], '');
    if (res.code !== 0) throw new Error(`install failed: ${res.stderr}`);
  }

  test('install writes a fenced block and removal restores the file byte-for-byte', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    const original = readFileSync(zshrc(), 'utf-8');
    cliInstall();
    expect(readFileSync(zshrc(), 'utf-8')).toContain('>>> genie shortcuts');

    expect(removeMarkedContent(zshrc(), MARKER)).toBe('removed');
    expect(readFileSync(zshrc(), 'utf-8')).toBe(original);
  });

  test('an edited interior is still removed whole — uninstall is version-proof', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    cliInstall();
    // Simulate a snippet shipped by a DIFFERENT release (or a user edit inside
    // the fence): the interior no longer matches this binary's generator.
    const drifted = readFileSync(zshrc(), 'utf-8').replace('stty -ixon 2>/dev/null', 'stty -ixon # v9 tweak');
    writeFileSync(zshrc(), drifted);

    expect(removeMarkedContent(zshrc(), MARKER)).toBe('removed');
    expect(readFileSync(zshrc(), 'utf-8')).toBe('export EDITOR=vim\n');
  });
});

describe('shortcuts CLI round-trip', () => {
  test('install then uninstall restores rc files byte-for-byte', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\nalias g=git\n');
    const original = readFileSync(zshrc(), 'utf-8');

    const installed = runShortcuts(['shortcuts', 'install', '--yes'], '');
    expect(installed.code).toBe(0);
    expect(existsSync(tmuxConf())).toBe(true);
    expect(readFileSync(zshrc(), 'utf-8')).not.toBe(original);

    const uninstalled = runShortcuts(['shortcuts', 'uninstall', '--yes'], '');
    expect(uninstalled.code).toBe(0);
    expect(uninstalled.stdout).toContain('✅ Uninstallation complete!');
    expect(readFileSync(zshrc(), 'utf-8')).toBe(original);
    // The rc file the user already had is restored; the tmux.conf install
    // invented is gone, not left as a 0-byte husk (dogfood r5 Z9).
    expect(existsSync(tmuxConf())).toBe(false);
  });

  /**
   * Regression (dogfood r5 Z9): install created ~/.tmux.conf in a HOME that had
   * none, uninstall stripped the block but kept the now-empty file, so every
   * install/uninstall cycle left a residual 0-byte config behind. The round trip
   * must return HOME to exactly what it was.
   */
  test('a HOME with no config files is left with none after install + uninstall', () => {
    expect(existsSync(tmuxConf())).toBe(false);
    expect(existsSync(join(dir, '.bashrc'))).toBe(false);

    const installed = runShortcuts(['shortcuts', 'install', '--yes'], '');
    expect(installed.code).toBe(0);
    expect(existsSync(tmuxConf())).toBe(true);
    expect(existsSync(join(dir, '.bashrc'))).toBe(true);

    const uninstalled = runShortcuts(['shortcuts', 'uninstall', '--yes'], '');
    expect(uninstalled.code).toBe(0);
    expect(uninstalled.stdout).toContain('file deleted — install created it');
    expect(existsSync(tmuxConf())).toBe(false);
    expect(existsSync(join(dir, '.bashrc'))).toBe(false);
  });

  /**
   * The other half of the same contract: a file the user already had — even a
   * deliberately empty one — is emptied, never deleted.
   */
  test('a pre-existing empty config survives the round trip as an empty file', () => {
    writeFileSync(tmuxConf(), '');

    expect(runShortcuts(['shortcuts', 'install', '--yes'], '').code).toBe(0);
    const uninstalled = runShortcuts(['shortcuts', 'uninstall', '--yes'], '');
    expect(uninstalled.code).toBe(0);
    const tmuxLine = uninstalled.stdout.split('\n').find((line) => line.includes(`Removed from ${tmuxConf()}`));
    expect(tmuxLine).toBe(`✅ Removed from ${tmuxConf()}`);
    expect(existsSync(tmuxConf())).toBe(true);
    expect(readFileSync(tmuxConf(), 'utf-8')).toBe('');
  });

  test('a second uninstall is a no-op and says so', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    runShortcuts(['shortcuts', 'install', '--yes'], '');
    const first = runShortcuts(['shortcuts', 'uninstall', '--yes'], '');
    expect(first.stdout).toContain('✅ Uninstallation complete!');
    const zshAfterFirst = readFileSync(zshrc(), 'utf-8');

    const second = runShortcuts(['shortcuts', 'uninstall', '--yes'], '');
    expect(second.code).toBe(0);
    expect(second.stdout).toContain('has no genie shortcuts');
    expect(readFileSync(zshrc(), 'utf-8')).toBe(zshAfterFirst);
  });
});

/**
 * The prompt machinery itself still has to work — it is what a real terminal
 * run uses. The CLI can no longer reach it off a TTY (see the non-interactive
 * contract below), so the decline path is driven through `installShortcuts`
 * directly, with `canPrompt` forced on and answers on stdin.
 */
describe('prompted run (the TTY path, driven directly)', () => {
  function runPrompted(answers: string): { code: number; stdout: string; stderr: string } {
    const runner = join(dir, 'runner.ts');
    writeFileSync(
      runner,
      [
        `import { installShortcuts } from ${JSON.stringify(realpathSync(join(import.meta.dir, 'shortcuts.ts')))};`,
        'const outcome = await installShortcuts({ canPrompt: true });',
        'process.stdout.write(`outcome=${outcome}\n`);',
        '',
      ].join('\n'),
    );
    const cmd = `printf '%b' ${JSON.stringify(answers)} | ${JSON.stringify(process.execPath)} ${JSON.stringify(runner)}`;
    const res = Bun.spawnSync(['/bin/sh', '-c', cmd], {
      stdout: 'pipe',
      stderr: 'pipe',
      timeout: 20_000,
      env: { ...process.env, HOME: dir, PATH: '/usr/bin:/bin' },
    });
    return { code: res.exitCode, stdout: res.stdout.toString(), stderr: res.stderr.toString() };
  }

  test('declining every target writes nothing and is a decision, not a failure', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    const original = readFileSync(zshrc(), 'utf-8');

    const res = runPrompted('n\nn\n');

    expect(res.stdout).toContain('Add shortcuts to');
    expect(res.stdout).toContain('outcome=declined');
    expect(res.stdout).not.toContain('Installation complete!');
    expect(readFileSync(zshrc(), 'utf-8')).toBe(original);
    expect(existsSync(tmuxConf())).toBe(false);
  });

  test('answers that run out mid-run are unanswered, not a partial success', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');

    const res = runPrompted('y\n');

    expect(res.stdout).toContain('outcome=unanswered');
    expect(res.stderr).toContain(shortcutsUnansweredMessage('install'));
    expect(readFileSync(zshrc(), 'utf-8')).toBe('export EDITOR=vim\n');
  });
});

/**
 * Dogfood M5 / c2: `genie shortcuts install` ignored `--no-interactive`, drew
 * both prompts, auto-answered them with "Skipped", printed "Installation
 * complete!" and exited 0 having written nothing — so every scripted or CI
 * invocation was a silent success no-op. The contract now has exactly two
 * non-interactive endings: apply the documented default (`--yes`), or exit
 * non-zero with a one-line reason.
 */
describe('shortcuts non-interactive contract (M5)', () => {
  test('--no-interactive refuses on one stderr line, exits 2, and writes nothing', () => {
    const res = runShortcuts(['--no-interactive', 'shortcuts', 'install'], '');
    expect(res.code).toBe(2);
    expect(res.stderr.trim()).toBe(shortcutsNonInteractiveMessage('install'));
    expect(res.stdout).not.toContain('Installation complete!');
    expect(res.stdout).not.toContain('Add shortcuts to'); // no prompt was rendered
    expect(existsSync(tmuxConf())).toBe(false);
    expect(existsSync(zshrc())).toBe(false);
    expect(existsSync(join(dir, '.bashrc'))).toBe(false);
  });

  test('--no-interactive --yes applies the documented default and exits 0', () => {
    const res = runShortcuts(['--no-interactive', 'shortcuts', 'install', '--yes'], '');
    expect(res.code).toBe(0);
    expect(res.stdout).toContain('Installation complete!');
    expect(readFileSync(tmuxConf(), 'utf-8')).toContain('>>> genie shortcuts');
    expect(readFileSync(join(dir, '.bashrc'), 'utf-8')).toContain('>>> genie shortcuts');
  });

  /**
   * Dogfood r2 §3.3 #2: the refusal was right, but stdout first carried
   * `Add shortcuts to …/.tmux.conf? [Y/n] ⏭️ Skipped tmux.conf — no answer on
   * stdin`. A question nobody can answer must never be drawn.
   */
  test('a non-TTY stdin refuses before any question reaches stdout', () => {
    const res = runShortcuts(['shortcuts', 'install'], '');
    expect(res.code).toBe(2);
    expect(res.stderr.trim()).toBe(shortcutsNonInteractiveMessage('install'));
    expect(res.stdout).not.toContain('Add shortcuts to');
    expect(res.stdout).not.toContain('[Y/n]');
    expect(res.stdout).not.toContain('Skipped');
    expect(res.stdout).not.toContain('Installation complete!');
    expect(existsSync(tmuxConf())).toBe(false);
    expect(existsSync(zshrc())).toBe(false);
    expect(existsSync(join(dir, '.bashrc'))).toBe(false);
  });

  test('piped answers are refused too — nothing is half-written', () => {
    writeFileSync(zshrc(), 'export EDITOR=vim\n');
    const res = runShortcuts(['shortcuts', 'install'], 'y\n');
    expect(res.code).toBe(2);
    expect(res.stderr.trim()).toBe(shortcutsNonInteractiveMessage('install'));
    expect(res.stdout).not.toContain('Add shortcuts to');
    expect(existsSync(tmuxConf())).toBe(false);
    expect(readFileSync(zshrc(), 'utf-8')).toBe('export EDITOR=vim\n');
  });

  /**
   * Dogfood r2 §3.3 #3: the old wording said "Re-run with --yes", and
   * `genie --no-interactive --yes shortcuts install` dies at Commander's parse
   * with `unknown option '--yes'`. The remedy must be copy-pasteable.
   */
  test('the refusal names an invocation that actually works', () => {
    const refusal = runShortcuts(['shortcuts', 'install'], '');
    const remedy = /Run: (genie shortcuts install --yes)/.exec(refusal.stderr)?.[1];
    expect(remedy).toBe('genie shortcuts install --yes');

    const applied = runShortcuts((remedy as string).split(' ').slice(1), '');
    expect(applied.code).toBe(0);
    expect(applied.stdout).toContain('Installation complete!');
  });

  test('the uninstall refusal names the uninstall remedy, not the install one', () => {
    const res = runShortcuts(['shortcuts', 'uninstall'], '');
    expect(res.code).toBe(2);
    expect(res.stderr.trim()).toBe(shortcutsNonInteractiveMessage('uninstall'));
    expect(res.stderr).toContain('Run: genie shortcuts uninstall --yes');
  });

  test('the unanswered message is verb-scoped too', () => {
    expect(shortcutsUnansweredMessage('install')).toContain('Run: genie shortcuts install --yes');
    expect(shortcutsUnansweredMessage('uninstall')).toContain('Run: genie shortcuts uninstall --yes');
  });

  test('uninstall honours the same contract', () => {
    expect(runShortcuts(['--no-interactive', 'shortcuts', 'install', '--yes'], '').code).toBe(0);

    const refused = runShortcuts(['--no-interactive', 'shortcuts', 'uninstall'], '');
    expect(refused.code).toBe(2);
    expect(refused.stderr.trim()).toBe(shortcutsNonInteractiveMessage('uninstall'));
    expect(readFileSync(tmuxConf(), 'utf-8')).toContain('>>> genie shortcuts');

    const applied = runShortcuts(['--no-interactive', 'shortcuts', 'uninstall', '--yes'], '');
    expect(applied.code).toBe(0);
    expect(applied.stdout).toContain('Uninstallation complete!');
    // install created this file in an empty HOME, so uninstall removes it whole.
    expect(existsSync(tmuxConf())).toBe(false);
  });

  test('--yes on a host with nothing to do is still a clean exit 0', () => {
    runShortcuts(['--no-interactive', 'shortcuts', 'install', '--yes'], '');
    const again = runShortcuts(['--no-interactive', 'shortcuts', 'install', '--yes'], '');
    expect(again.code).toBe(0);
    expect(again.stdout).toContain('already has genie shortcuts');
  });
});
